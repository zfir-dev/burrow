import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { unitDir } from '../service.js';

// systemd user unit that keeps "burrow ai connect" running (Linux). On macOS, run it
// from a launchd agent instead; the README has an example plist.
export const AI_UNIT = 'burrow-ai-connect.service';
const BIN = fileURLToPath(new URL('../../bin/burrow.js', import.meta.url));
export const aiUnitPath = () => join(unitDir(), AI_UNIT);

const q = (v) => (/^[A-Za-z0-9_@%+=:,./-]+$/.test(v) ? v : `"${String(v).replace(/(["\\])/g, '\\$1')}"`);

// Records the current node binary and PATH (nvm installs live in versioned folders),
// like burrow's own units.
export function renderAiUnit({ env = process.env, node = process.execPath, bin = BIN } = {}) {
  const keep = ['PATH', 'BURROW_CONFIG', 'BURROW_STATE_DIR', 'XDG_CONFIG_HOME', 'XDG_STATE_HOME', 'BURROW_AI_CONFIG_DIR', 'BURROW_AI_STATE_DIR'];
  const envLines = keep.filter((k) => env[k]).map((k) => `Environment=${q(`${k}=${env[k]}`)}`);
  return `# Generated by "burrow ai connect --install-service". Remove with "burrow ai connect --uninstall-service".
[Unit]
Description=burrow ai connect: lets your AI agents use burrow through burrow-ai
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
${envLines.join('\n')}
ExecStart=${[node, bin, 'ai', 'connect'].map(q).join(' ')}
Restart=always
RestartSec=10

[Install]
WantedBy=default.target
`;
}

function systemctl(...args) {
  const r = spawnSync(process.env.BURROW_SYSTEMCTL || 'systemctl', ['--user', ...args], { encoding: 'utf8', timeout: 30000, killSignal: 'SIGKILL' });
  return { ok: !r.error && r.status === 0, out: `${r.stdout || ''}${r.stderr || ''}`.trim(), error: r.error };
}

export function installAiService({ dryRun = false, now = true, log = console.log } = {}) {
  const path = aiUnitPath();
  const unit = renderAiUnit();
  if (dryRun) { log(`[dry-run] would write ${path}:\n`); log(unit); return { path, unit, dryRun: true }; }
  if (process.platform !== 'linux') throw new Error('--install-service writes a systemd user unit (Linux only); on macOS see "burrow ai" in the README for a launchd plist');
  mkdirSync(unitDir(), { recursive: true });
  writeFileSync(path, unit);
  for (const args of [['daemon-reload'], ['enable', ...(now ? ['--now'] : []), AI_UNIT]]) {
    const r = systemctl(...args);
    if (!r.ok) throw new Error(`systemctl --user ${args.join(' ')} failed: ${r.error?.message || r.out}`);
  }
  log(`Wrote ${path} and ${now ? 'started' : 'enabled'} ${AI_UNIT}. Logs: journalctl --user -u ${AI_UNIT} -f`);
  return { path, unit };
}

export function uninstallAiService({ dryRun = false, log = console.log } = {}) {
  const path = aiUnitPath();
  if (dryRun) { log(`[dry-run] would disable ${AI_UNIT} and remove ${path}`); return { path, dryRun: true }; }
  systemctl('disable', '--now', AI_UNIT);
  rmSync(path, { force: true });
  systemctl('daemon-reload');
  log(`Removed ${AI_UNIT}.`);
  return { path };
}

export function aiServiceStatus() {
  if (!existsSync(aiUnitPath())) return 'not installed';
  const r = systemctl('is-active', AI_UNIT);
  return r.out.split('\n')[0] || (r.ok ? 'active' : 'inactive');
}
