import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { homedir, userInfo } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadConfig, stateDir } from './config.js';
import { loadProjectFile, DASHBOARD_PROJECT } from './project.js';
import { readMeta } from './process.js';

export const UNIT_NAME = 'burrow.service';
const BIN = fileURLToPath(new URL('../bin/burrow.js', import.meta.url));
const log = (...a) => console.log(...a);

export const unitDir = () =>
  process.env.BURROW_SYSTEMD_DIR || join(process.env.XDG_CONFIG_HOME || join(homedir(), '.config'), 'systemd', 'user');
export const unitPath = () => join(unitDir(), UNIT_NAME);
const systemctlBin = () => process.env.BURROW_SYSTEMCTL || 'systemctl';

function systemctl(...args) {
  const r = spawnSync(systemctlBin(), ['--user', ...args], { encoding: 'utf8' });
  return { ok: !r.error && r.status === 0, out: `${r.stdout || ''}${r.stderr || ''}`.trim(), error: r.error };
}

// systemd-run (to start the boot command in its own transient scope), or null. BURROW_SYSTEMD_RUN
// overrides the binary; "none" turns it off. Without it the unit behaves as before.
export function findSystemdRun(env = process.env) {
  const v = env.BURROW_SYSTEMD_RUN;
  if (v === 'none') return null;
  if (v) return v;
  for (const dir of (env.PATH || '').split(':').filter(Boolean)) {
    const f = join(dir, 'systemd-run');
    if (existsSync(f)) return f;
  }
  return null;
}

// systemd quoting for Environment= and Exec lines.
const q = (s) => (/^[A-Za-z0-9_@%+=:,./-]+$/.test(s) ? s : `"${String(s).replace(/(["\\])/g, '\\$1')}"`);

export function renderUnit({ node = process.execPath, bin = BIN, projects = [], env = process.env, systemdRun = findSystemdRun(env) } = {}) {
  const keep = ['PATH', 'BURROW_CONFIG', 'BURROW_STATE_DIR', 'XDG_CONFIG_HOME', 'XDG_STATE_HOME'];
  const envLines = keep.filter((k) => env[k]).map((k) => `Environment=${q(`${k}=${env[k]}`)}`);
  // Run the boot command in its own transient scope so the connectors, dashboard, shares and
  // expiry watchers it starts live outside this unit's cgroup: systemd then has nothing left
  // over to warn about when the unit stops or restarts.
  const scope = systemdRun ? [systemdRun, '--user', '--scope', '--quiet', '--description=burrow: tunnels, dashboard and shares'] : [];
  const start = [...scope, node, bin, 'autostart', ...projects].map(q).join(' ');
  const stop = [node, bin, 'down', '--keep-shares'].map(q).join(' ');
  return `# Generated by "burrow service install". Remove with "burrow service uninstall".
[Unit]
Description=burrow: Cloudflare Tunnels for local projects
Wants=network-online.target
After=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
${envLines.join('\n')}
ExecStart=${start}
ExecStop=${stop}
TimeoutStartSec=300
# Connectors, the dashboard, shares and their expiry watchers are detached children of the boot
# command${systemdRun ? ', which runs in its own systemd scope (systemd-run --scope), outside this unit' : ''}.
# Stopping or restarting the unit runs ExecStop (which stops the projects but keeps shares)
# and then kills only the main process, not the whole control group.
KillMode=process

[Install]
WantedBy=default.target
`;
}

// A unit written by an older burrow, without KillMode=process: stopping or restarting it
// kills every process it started (including shares). "burrow service install" rewrites it.
export function unitOutdated(path = unitPath(), systemdRun = findSystemdRun()) {
  return unitProblem(path, systemdRun) !== null;
}
// null, 'killmode' (no KillMode=process) or 'scope' (systemd-run is available but the unit
// doesn't start its boot command in a scope, so systemd warns about leftover processes).
export function unitProblem(path = unitPath(), systemdRun = findSystemdRun()) {
  let text;
  try { text = readFileSync(path, 'utf8'); } catch { return null; }
  if (!/^KillMode=process$/m.test(text)) return 'killmode';
  if (systemdRun && !/^ExecStart=.*\s--scope\s/m.test(text)) return 'scope';
  return null;
}
export const OUTDATED_HINT = 'written by an older burrow: stopping or restarting it also kills shares and the dashboard. Run "burrow service install" to update it.';
export const SCOPE_HINT = 'its boot command is not started in a systemd scope, so systemd warns about leftover processes (shares, dashboard) when it stops or restarts. Run "burrow service install" to update it.';
export const outdatedHint = (path = unitPath(), systemdRun = findSystemdRun()) => (unitProblem(path, systemdRun) === 'scope' ? SCOPE_HINT : OUTDATED_HINT);

// Projects to bring up at boot: BURROW_AUTOSTART in the config plus every
// remembered project whose tunnel.yml has `autostart: true`.
export function autostartProjects(cfg = loadConfig()) {
  const list = (cfg.autostart || '').split(',').map((s) => s.trim()).filter(Boolean);
  let metas = [];
  try { metas = readdirSync(stateDir()).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)); } catch {}
  for (const name of metas.sort()) {
    const file = readMeta(name)?.file;
    if (!file || !existsSync(file)) continue;
    try { if (loadProjectFile(file).autostart) list.push(name); } catch {}
  }
  return [...new Set(list)];
}

export async function autostart(projectArgs = [], opts = {}) {
  const projects = projectArgs.length ? projectArgs : autostartProjects();
  if (!projects.length) {
    log('No autostart projects. Set "autostart: true" in a tunnel.yml or BURROW_AUTOSTART in the config.');
    return;
  }
  if (opts.dryRun) { log(`[dry-run] would bring up: ${projects.join(', ')}`); return; }
  const cmd = await import('./commands.js');
  let failed = 0;
  for (const p of projects) {
    try {
      if (p === DASHBOARD_PROJECT) await (await import('./dashboard/manage.js')).up({});
      else await cmd.up(p, {});
    } catch (e) {
      failed++;
      console.error(`burrow: ${p}: ${e.message}`);
    }
  }
  if (failed) process.exitCode = 1;
}

function lingerHint() {
  const user = userInfo().username;
  const r = spawnSync('loginctl', ['show-user', user, '-p', 'Linger', '--value'], { encoding: 'utf8' });
  if (r.error || r.status !== 0) return null;
  return r.stdout.trim() === 'yes' ? 'yes' : `no (run "loginctl enable-linger ${user}" so it starts at boot without logging in)`;
}

export async function service(action, opts = {}) {
  const projects = (opts.projects || '').split(',').map((s) => s.trim()).filter(Boolean);
  if (action === 'install') {
    const unit = renderUnit({ projects });
    if (opts.dryRun) { log(`[dry-run] would write ${unitPath()}:\n`); log(unit); return; }
    const upgraded = unitOutdated();
    mkdirSync(unitDir(), { recursive: true });
    writeFileSync(unitPath(), unit);
    log(`Wrote ${unitPath()}${upgraded ? ' (replaced an older unit; stopping the service now leaves shares and the dashboard running)' : ''}`);
    for (const args of [['daemon-reload'], ['enable', ...(opts.now ? ['--now'] : []), UNIT_NAME]]) {
      const r = systemctl(...args);
      if (!r.ok) throw new Error(`systemctl --user ${args.join(' ')} failed: ${r.error?.message || r.out}`);
    }
    log(`Enabled ${UNIT_NAME}${opts.now ? ' and started it' : ''}.`);
    const list = projects.length ? projects : autostartProjects();
    log(`Projects at boot: ${list.length ? list.join(', ') : '(none yet; add autostart: true or BURROW_AUTOSTART)'}${projects.length ? '' : ' (re-read at every boot)'}`);
    const linger = lingerHint();
    if (linger && linger !== 'yes') log(`Linger: ${linger}`);
    return;
  }
  if (action === 'uninstall') {
    if (opts.dryRun) { log(`[dry-run] would disable ${UNIT_NAME} and remove ${unitPath()}`); return; }
    systemctl('disable', '--now', UNIT_NAME);
    rmSync(unitPath(), { force: true });
    systemctl('daemon-reload');
    log(`Removed ${UNIT_NAME}. Its stop command stopped the running connectors (shares were kept); start them again with burrow up.`);
    return;
  }
  if (action === 'status') {
    log(`Unit: ${existsSync(unitPath()) ? unitPath() : 'not installed'}`);
    if (unitOutdated()) log(`Outdated: ${outdatedHint()}`);
    log(`Enabled: ${systemctl('is-enabled', UNIT_NAME).out || 'unknown'}`);
    log(`Active: ${systemctl('is-active', UNIT_NAME).out || 'unknown'}`);
    const list = autostartProjects();
    log(`Autostart projects: ${list.length ? list.join(', ') : 'none'}`);
    const linger = lingerHint();
    if (linger) log(`Linger: ${linger}`);
    return;
  }
  throw new Error(`Unknown service action "${action}" (use install, uninstall or status)`);
}
